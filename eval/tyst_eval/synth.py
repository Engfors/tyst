"""`python -m tyst_eval synth`: synthetic smoke-test clips from Piper voices.

TTS speech is far cleaner than a real meeting and the Swedish voice reads English words with
Swedish phonetics, so these numbers only show that the pipeline works end to end. They are not
evidence for any Phase 0 decision.
"""

from __future__ import annotations

from math import gcd

import numpy as np

from .config import load_manifest, load_models
from .fetch import _write_wav, write_manifest

SV = [
    "Hej allihop, vi börjar med en snabb genomgång av veckans arbete.",
    "Jag har pratat med kunden och de vill ha en ny version innan månadsskiftet.",
    "Det finns några frågor kring hur vi ska hantera inloggningen.",
    "Vi behöver också bestämma vem som tar hand om dokumentationen.",
    "Kan du skicka över anteckningarna efter mötet?",
    "Jag tror att vi hinner klart om vi prioriterar rätt saker.",
    "Budgeten för nästa kvartal är inte bestämd ännu.",
    "Vi ses igen på torsdag klockan tio.",
]
EN = [
    "Sorry I'm late, should we switch to English?",
    "Sure, no problem, let's continue in English.",
    "I think the main risk is the migration of the old database.",
    "Can you share the timeline with the rest of the team?",
    "We should have a first draft ready by the end of next week.",
    "Let me check with the security team and get back to you.",
    "The customer asked for a short demo on Friday.",
    "That sounds good to me, thanks everyone.",
]
SV_TERMS = [
    "Vi måste fixa vår Terraform state drift innan deploy.",
    "Har någon kollat om Vault-tokenet har gått ut?",
    "Vi kör allt i Kubernetes men databasen ligger utanför klustret.",
    "HashiCorp har släppt en ny version av Terraform.",
    "Jag skapade en pull request i GitHub i morse.",
    "Kan du lägga till en ny secret i Vault för staging?",
    "Vår pipeline bygger en container och pushar den till registret.",
    "Vi behöver uppdatera Helm-chartet innan vi rullar ut.",
]


def _voice(models, mid):
    import sherpa_onnx

    d = models[mid].path
    onnx = next(d.glob("*.onnx"))
    cfg = sherpa_onnx.OfflineTtsConfig(
        model=sherpa_onnx.OfflineTtsModelConfig(
            vits=sherpa_onnx.OfflineTtsVitsModelConfig(model=str(onnx), tokens=str(d / "tokens.txt"), data_dir=str(d / "espeak-ng-data")),
            num_threads=4,
        )
    )
    return sherpa_onnx.OfflineTts(cfg)


def synth(args) -> None:
    from scipy.signal import resample_poly

    models = load_models()
    voices = {"sv": _voice(models, "piper-sv"), "en": _voice(models, "piper-en")}
    _, _, root = load_manifest()
    out = root / "synth"
    out.mkdir(parents=True, exist_ok=True)
    gap = np.zeros(int(0.7 * 16000), dtype=np.float32)

    def say(lang: str, text: str) -> np.ndarray:
        a = voices[lang].generate(text)
        pcm = np.asarray(a.samples, dtype=np.float32)
        if a.sample_rate == 16000:
            return pcm
        g = gcd(a.sample_rate, 16000)
        return resample_poly(pcm, 16000 // g, a.sample_rate // g).astype(np.float32)

    entries = []

    def clip(cid: str, cat: str, lang: str, plan: list[tuple[str, str]]) -> None:
        parts, spans, t = [], [], 0.0
        for l, text in plan:
            pcm = say(l, text)
            parts += [pcm, gap]
            dur = (len(pcm) + len(gap)) / 16000
            if spans and spans[-1][2] == l:
                spans[-1][1] = round(t + dur, 2)
            else:
                spans.append([round(t, 2), round(t + dur, 2), l])
            t += dur
        _write_wav(out / f"{cid}.wav", np.concatenate(parts))
        (out / f"{cid}.txt").write_text(" ".join(t for _, t in plan) + "\n", encoding="utf-8")
        entries.append((cid, cat, lang, spans if len(spans) > 1 else []))

    for k in range(args.n):
        rot = lambda xs, n=4: [xs[(k + i) % len(xs)] for i in range(n)]  # noqa: E731
        clip(f"synth-sv-{k + 1:02d}", "synth-sv", "sv", [("sv", s) for s in rot(SV)])
        clip(f"synth-en-{k + 1:02d}", "synth-en", "en", [("en", s) for s in rot(EN)])
        clip(f"synth-terms-{k + 1:02d}", "synth-terms", "sv", [("sv", s) for s in rot(SV_TERMS, 3)])
        clip(f"synth-mixed-{k + 1:02d}", "synth-mixed", "sv",
             [("sv", s) for s in rot(SV, 2)] + [("en", s) for s in rot(EN, 3)] + [("sv", SV[k % len(SV)])])
    write_manifest(out / "manifest.toml", entries, "synth", "Generated by `python -m tyst_eval synth` (Piper TTS). Smoke test only.")
    print(f"wrote {len(entries)} synthetic clips to {out}")
